import path from "node:path";
import { spawnSync } from "node:child_process";
import { validateWebProjectManifestV2 } from "./web-project-manifest-v2.mjs";

function quote(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function shellQuote(value) {
  const text = String(value);
  if (/^[A-Za-z0-9_./:@%+=,-]+$/.test(text)) return text;
  return `'${text.replaceAll("'", `'"'"'`)}'`;
}

function shellCommand(argv) {
  return argv.map(shellQuote).join(" ");
}

function currentGitRevision(cwd) {
  const result = spawnSync("git", ["rev-parse", "HEAD"], { cwd, encoding: "utf8", shell: false });
  return result.status === 0 && /^[0-9a-f]{40}$/.test(result.stdout.trim()) ? result.stdout.trim() : null;
}

function step(lines, item) {
  lines.push(`      - name: ${item.name}`);
  if (item.if) lines.push(`        if: ${item.if}`);
  if (item.uses) lines.push(`        uses: ${item.uses}`);
  if (item.with) {
    lines.push("        with:");
    for (const [key, value] of Object.entries(item.with)) lines.push(`          ${key}: ${quote(value)}`);
  }
  if (item.workingDirectory) lines.push(`        working-directory: ${quote(item.workingDirectory)}`);
  if (item.run) {
    if (item.run.includes("\n")) {
      lines.push("        run: |");
      for (const line of item.run.split("\n")) lines.push(`          ${line}`);
    } else lines.push(`        run: ${item.run}`);
  }
}

export function generateGitHubActionsWorkflow(manifest, {
  manifestPath = "proped.web.json",
  propedRepository = "f4ah6o/Proped",
  propedRef = null,
  toolCheckoutPath = ".proped/tool",
  nodeVersion = "22",
  toolRoot = process.cwd(),
} = {}) {
  validateWebProjectManifestV2(manifest);
  const resolvedRef = propedRef ?? currentGitRevision(toolRoot);
  if (!resolvedRef) throw new Error("GitHub Actions workflow generation requires an explicit --proped-ref when the tool revision cannot be resolved");
  if (!/^[0-9a-f]{40}$/.test(resolvedRef)) throw new Error("Proped workflow ref must be a full 40-character commit SHA");
  if (manifest.server.mode === "review-required") throw new Error("server.mode review-required must be resolved before generating CI");

  const projectRoot = manifest.project.root;
  const toolBrowserRoot = `${toolCheckoutPath}/web/playwright-browser`;
  const steps = [];
  steps.push({ name: "Checkout project", uses: "actions/checkout@v4" });
  steps.push({
    name: "Checkout pinned Proped",
    uses: "actions/checkout@v4",
    with: { repository: propedRepository, ref: resolvedRef, path: toolCheckoutPath },
  });
  steps.push({ name: "Setup Node.js", uses: "actions/setup-node@v4", with: { "node-version": nodeVersion } });
  if (["pnpm", "yarn"].includes(manifest.project.packageManager)) steps.push({ name: "Enable Corepack", run: "corepack enable" });
  if (manifest.bootstrap.install) {
    steps.push({
      name: "Install project dependencies",
      workingDirectory: projectRoot,
      run: shellCommand(manifest.bootstrap.install),
    });
  }
  steps.push({
    name: "Install Proped browser runtime",
    run: `npm ci --prefix ${shellQuote(toolBrowserRoot)} --ignore-scripts`,
  });
  steps.push({
    name: "Install Chromium and Linux dependencies",
    run: `npx --prefix ${shellQuote(toolBrowserRoot)} playwright install --with-deps --only-shell chromium`,
  });
  if (manifest.sandbox.mode === "strict") {
    steps.push({
      name: "Install strict sandbox backend",
      run: "sudo apt-get update\nsudo apt-get install --yes bubblewrap",
    });
  }
  steps.push({
    name: "Run Proped Web quality gate",
    run: `node ${shellQuote(`${toolCheckoutPath}/scripts/web_project_run_v2.mjs`)} ${shellQuote(manifestPath)} --repository-root .`,
  });
  steps.push({
    name: "Upload Proped artifacts",
    if: "always()",
    uses: "actions/upload-artifact@v4",
    with: { name: "proped-web-artifacts", path: manifest.artifacts.output, "if-no-files-found": "error" },
  });

  const lines = [
    "# Generated by Proped. The tool checkout is pinned to a full commit SHA.",
    "name: Proped Web Quality",
    "",
    "on:",
    "  pull_request:",
    "  push:",
    "    branches:",
    "      - main",
    "  workflow_dispatch:",
    "",
    "permissions:",
    "  contents: read",
    "",
    "jobs:",
    "  proped-web:",
    "    runs-on: ubuntu-latest",
    "    timeout-minutes: 30",
    "    steps:",
  ];
  for (const item of steps) step(lines, item);
  lines.push("");
  return {
    workflow: lines.join("\n"),
    metadata: {
      propedRepository,
      propedRef: resolvedRef,
      toolCheckoutPath,
      nodeVersion,
      projectRoot,
      manifestPath,
      strictSandbox: manifest.sandbox.mode === "strict",
      bootstrapInstall: manifest.bootstrap.install,
    },
  };
}
